#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	char	*p;

	p = (char *)s;
	while (1)
	{
		if (*p == (char)c)
			return (p);
		if (*p == '\0')
			return (NULL);
		p++;
	}
}
